-- Public data: only active services, visible reviews, and safe settings.
create policy "public active services" on public.services for select to anon using (active=true);
create policy "public visible reviews" on public.reviews for select to anon using (visible=true);
create policy "public settings read" on public.settings for select to anon using (id=1);

-- Admin access, protected by Supabase Auth + admin_users membership.
create policy "admins admin_users" on public.admin_users for select to authenticated using (public.is_admin());
create policy "admins settings" on public.settings for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admins services" on public.services for all to authenticated using (public.is_admin()) with check (public.is_admin());
