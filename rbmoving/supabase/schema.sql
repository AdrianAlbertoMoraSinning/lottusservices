  id integer primary key default 1 check (id=1),
  gst_rate numeric(5,2) not null default 5.00,
  business_hours text not null default '8:00 AM–8:00 PM',
  booking_slots text[] not null default array['8:00 AM','9:00 AM','10:00 AM','11:00 AM','12:00 PM','1:00 PM','2:00 PM','3:00 PM','4:00 PM','5:00 PM','6:00 PM'],
  timezone text not null default 'America/Edmonton',
