create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  first_name text not null,
  last_name text not null,
  phone text not null,
  email text not null,
  service_date date not null,
  start_slot text not null,
  origin text not null,
  destination text not null,
  details text,
  subtotal numeric(10,2) not null,
  gst_amount numeric(10,2) not null,
  total_estimate numeric(10,2) not null,
  status text not null default 'Confirmed',
  job_status text not null default 'Scheduled',
  invoice_status text not null default 'Not Issued',
  payment_status text not null default 'Not Required Yet',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists bookings_active_slot_unique on public.bookings(service_date,start_slot) where lower(status) <> 'cancelled';

create table if not exists public.booking_items (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings(id) on delete cascade,
  service_id text references public.services(id),
  service_name text not null,
  qty numeric(8,2) not null,
  unit_price numeric(10,2) not null,
  unit text not null,
  line_total numeric(10,2) not null
);

create table if not exists public.availability_blocks (
  id bigint generated by default as identity primary key,
  block_date date not null,
  start_slot text,
  reason text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists availability_blocks_date_idx on public.availability_blocks(block_date);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  google_review_id text unique,
  author text not null,
  rating integer not null check (rating between 1 and 5),
  review_text text not null,
  review_date date,
  source text not null default 'Google',
  source_url text,
  visible boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number text not null unique,
  booking_id uuid references public.bookings(id) on delete set null,
  public_token text not null unique default encode(gen_random_bytes(18),'hex'),
  client_name text,
  client_email text,
  client_phone text,
  invoice_date date not null default current_date,
  subtotal numeric(10,2),
  gst_rate numeric(5,2) not null default 5.00,
  gst_amount numeric(10,2),
  total_amount numeric(10,2),
  final_amount numeric(10,2) not null check(final_amount > 0),
  status text not null default 'Draft',
  note text,
  issued_at timestamptz not null default now(),
  due_date date,
  updated_at timestamptz not null default now()
);

create table if not exists public.invoice_items (
  id bigint generated by default as identity primary key,
  invoice_id uuid not null references public.invoices(id) on delete cascade,
  description text not null,
  qty numeric(10,2) not null default 1 check(qty > 0),
  unit text not null default 'hour',
  unit_rate numeric(10,2) not null default 0 check(unit_rate >= 0),
  line_total numeric(10,2) not null default 0 check(line_total >= 0),
  sort_order integer not null default 100
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.admin_users where user_id=auth.uid());
$$;

create or replace function public.get_public_day_availability(p_date date)
returns table(slot_label text,state text)
language sql stable security definer set search_path=public as $$
  with slots as (
    select unnest(coalesce((select booking_slots from public.settings where id=1), array['8:00 AM','9:00 AM','10:00 AM','11:00 AM','12:00 PM','1:00 PM','2:00 PM','3:00 PM','4:00 PM','5:00 PM','6:00 PM'])) as slot_label
  )
  select s.slot_label,
    case
      when exists(select 1 from public.bookings b where b.service_date=p_date and b.start_slot=s.slot_label and lower(b.status)<>'cancelled') then 'booked'
      when exists(select 1 from public.availability_blocks a where a.block_date=p_date and a.active and (a.start_slot is null or a.start_slot=s.slot_label)) then 'unavailable'
      else 'available'
    end as state
  from slots s;
$$;

create or replace function public.create_public_booking(
  p_first_name text,
  p_last_name text,
  p_phone text,
  p_email text,
  p_service_date date,
  p_start_slot text,
  p_origin text,
  p_destination text,
  p_details text,
  p_items jsonb
)
returns table(booking_reference text,subtotal numeric,gst_amount numeric,total_estimate numeric)
language plpgsql security definer set search_path=public as $$
declare
  v_id uuid;
  v_ref text;
  v_subtotal numeric(10,2);
  v_gst_rate numeric(5,2);
  v_gst numeric(10,2);
  v_total numeric(10,2);
  v_count integer;
begin
  if p_service_date < current_date then raise exception 'INVALID_DATE'; end if;
  if not exists(select 1 from unnest((select booking_slots from public.settings where id=1)) x where x=p_start_slot) then raise exception 'INVALID_SLOT'; end if;
  if exists(select 1 from public.availability_blocks a where a.block_date=p_service_date and a.active and (a.start_slot is null or a.start_slot=p_start_slot)) then raise exception 'SLOT_BLOCKED'; end if;
  if exists(select 1 from public.bookings b where b.service_date=p_service_date and b.start_slot=p_start_slot and lower(b.status)<>'cancelled') then raise exception 'SLOT_UNAVAILABLE'; end if;

  with requested as (
    select x.service_id, greatest(x.qty, s.minimum) qty, s.name, s.price, s.unit
    from jsonb_to_recordset(coalesce(p_items,'[]'::jsonb)) as x(service_id text, qty numeric)
    join public.services s on s.id=x.service_id and s.active=true
  )
  select count(*),coalesce(sum(qty*price),0) into v_count,v_subtotal from requested;
  if v_count=0 or v_subtotal<=0 then raise exception 'NO_VALID_SERVICES'; end if;

  select gst_rate into v_gst_rate from public.settings where id=1;
  v_gst=round(v_subtotal*(coalesce(v_gst_rate,5)/100),2); v_total=v_subtotal+v_gst;
  v_ref='RB-'||to_char(p_service_date,'YYYYMMDD')||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));

  begin
    insert into public.bookings(reference,first_name,last_name,phone,email,service_date,start_slot,origin,destination,details,subtotal,gst_amount,total_estimate)
    values(v_ref,trim(p_first_name),trim(p_last_name),trim(p_phone),lower(trim(p_email)),p_service_date,p_start_slot,trim(p_origin),trim(p_destination),nullif(trim(p_details),''),v_subtotal,v_gst,v_total)
    returning id into v_id;
  exception when unique_violation then
    raise exception 'SLOT_UNAVAILABLE';
  end;

  insert into public.booking_items(booking_id,service_id,service_name,qty,unit_price,unit,line_total)
  select v_id,s.id,s.name,greatest(x.qty,s.minimum),s.price,s.unit,round(greatest(x.qty,s.minimum)*s.price,2)
  from jsonb_to_recordset(p_items) as x(service_id text, qty numeric)
  join public.services s on s.id=x.service_id and s.active=true;

  return query select v_ref,v_subtotal,v_gst,v_total;
end;
$$;

create or replace function public.get_public_invoice(p_invoice_number text)
returns table(invoice_number text,booking_reference text,final_amount numeric,status text)
language sql stable security definer set search_path=public as $$
 select i.invoice_number,b.reference,i.final_amount,i.status from public.invoices i join public.bookings b on b.id=i.booking_id where i.invoice_number=p_invoice_number limit 1;
$$;

create or replace function public.get_public_invoice_by_token(p_token text)
returns jsonb
language sql stable security definer set search_path=public as $$
  select jsonb_build_object(
    'invoice_number', i.invoice_number,
    'invoice_date', i.invoice_date,
    'due_date', i.due_date,
    'status', i.status,
    'client_name', coalesce(i.client_name, trim(coalesce(b.first_name,'') || ' ' || coalesce(b.last_name,''))),
    'client_email', coalesce(i.client_email,b.email),
    'client_phone', coalesce(i.client_phone,b.phone),
    'booking_reference', b.reference,
    'service_date', b.service_date,
    'origin', b.origin,
    'destination', b.destination,
    'subtotal', coalesce(i.subtotal, i.final_amount),
    'gst_rate', coalesce(i.gst_rate,0),
    'gst_amount', coalesce(i.gst_amount,0),
    'total_amount', coalesce(i.total_amount,i.final_amount),
    'final_amount', coalesce(i.total_amount,i.final_amount),
    'note', i.note,
    'public_token', i.public_token,
    'items', coalesce((select jsonb_agg(jsonb_build_object('description',ii.description,'qty',ii.qty,'unit',ii.unit,'unit_rate',ii.unit_rate,'line_total',ii.line_total) order by ii.sort_order,ii.id) from public.invoice_items ii where ii.invoice_id=i.id),'[]'::jsonb)
  ) from public.invoices i left join public.bookings b on b.id=i.booking_id where i.public_token=p_token limit 1;
$$;


